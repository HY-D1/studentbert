#!/usr/bin/env python3
"""Guard analysis/collect_all_results.py against destroying hand-added sections.

The script currently ends with a blind `open(args.out_md,"w")`, so running it
overwrites RESULTS.md wholesale. Six blocks are NOT regenerated by it and would
be lost: 2.1, 3.1, 3.2, 6.1, 8.1, 8.2, plus the section 10 appendix. Several of
those were reconstructed from logs at some cost.

This inserts a pre-write check: if the target already contains any of those
markers, the script refuses and tells you to write elsewhere, unless --force is
passed. Nothing about the collection logic changes.

Run from the repo root:  python3 tools/patches/guard_collect_all_results.py
Idempotent.
"""
import sys

PATH = "analysis/collect_all_results.py"

OLD_ARG = '''    ap.add_argument("--out_json", default="results.json")
    args = ap.parse_args()'''
NEW_ARG = '''    ap.add_argument("--out_json", default="results.json")
    ap.add_argument("--force", action="store_true",
                    help="overwrite --out_md even if it contains hand-added sections")
    args = ap.parse_args()

    # Sections this script does NOT regenerate. Overwriting RESULTS.md while any
    # of them are present silently destroys them.
    MANUAL = ["### 2.1", "### 3.1", "### 3.2", "### 6.1", "### 8.1", "### 8.2", "## 10."]
    if os.path.exists(args.out_md) and not args.force:
        existing = open(args.out_md, errors="ignore").read()
        present = [m for m in MANUAL if m in existing]
        if present:
            sys.exit(
                f"REFUSING to overwrite {args.out_md}: it contains hand-added sections "
                f"that this script does not regenerate ({', '.join(present)}).\\n"
                f"  Write elsewhere and diff:  --out_md RESULTS_generated.md\\n"
                f"  Or overwrite deliberately: --force  (the sections above will be lost)")'''

OLD_IMP = "import argparse"
NEW_IMP = "import argparse\nimport os\nimport sys"

src = open(PATH).read()
if "REFUSING to overwrite" in src:
    sys.exit("ALREADY GUARDED. Nothing done.")

if OLD_ARG not in src:
    sys.exit(f"ERROR: argparse block not found verbatim in {PATH}; guard by hand near main()")
src = src.replace(OLD_ARG, NEW_ARG, 1)

if "\nimport os" not in src or "\nimport sys" not in src:
    if OLD_IMP not in src:
        sys.exit(f"ERROR: cannot find 'import argparse' in {PATH} to add os/sys")
    src = src.replace(OLD_IMP, NEW_IMP, 1)

open(PATH, "w").write(src)
print(f"GUARDED {PATH}.")
print("Behaviour now: refuses to overwrite RESULTS.md while 2.1/3.1/3.2/6.1/8.1/8.2/10 exist.")
print("Verify: python3 analysis/collect_all_results.py --logdir . | tail -3")
